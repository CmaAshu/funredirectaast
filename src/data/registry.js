// Dynamic import — mode: 'mcq' | 'pyq' | 'sjc'
export async function loadQuizData(paperId, mode = 'mcq') {
  const meta = paperRegistry[paperId]
  if (!meta) return null
  try {
    let fileName
    if (mode === 'pyq' && meta.pyqFile) {
      fileName = meta.pyqFile
    } else if (mode === 'sjc' && meta.sjcFile) {
      fileName = meta.sjcFile
    } else {
      fileName = meta.dataFile
    }
    const loader = dataImports[fileName]
    if (!loader) return null
    const mod = await loader()
    return mod.quizSets ?? null
  } catch {
    return null
  }
}
